import assert from 'node:assert/strict';
import { schedule, addCalendarDays, localDay } from './review-reference.mjs';

let checks = 0;
const check = fn => { fn(); checks += 1; };
const first = schedule(null, {day:'2026-10-17',outcome:'correct'});
check(()=>assert.equal(first.stage,0));
check(()=>assert.equal(first.dueDay,'2026-10-18'));
check(()=>assert.equal(first.independentSuccesses,1));
const sameDay=schedule(first,{day:'2026-10-17',outcome:'correct'});
check(()=>assert.equal(sameDay.stage,0));
check(()=>assert.equal(sameDay.independentSuccesses,1));
const due=schedule(first,{day:'2026-10-18',outcome:'correct'});
check(()=>assert.equal(due.stage,1));
check(()=>assert.equal(due.dueDay,'2026-10-21'));
const early=schedule(due,{day:'2026-10-19',outcome:'correct'});
check(()=>assert.equal(early.dueDay,'2026-10-21'));
check(()=>assert.equal(early.stage,1));
const hinted=schedule(due,{day:'2026-10-19',outcome:'hinted'});
check(()=>assert.equal(hinted.stage,1));
check(()=>assert.equal(hinted.dueDay,'2026-10-20'));
check(()=>assert.equal(hinted.independentSuccesses,2));
const wrong=schedule(due,{day:'2026-10-19',outcome:'incorrect'});
check(()=>assert.equal(wrong.stage,0));
check(()=>assert.equal(wrong.lapses,1));
check(()=>assert.equal(wrong.dueDay,'2026-10-20'));
const overdue=schedule(first,{day:'2026-12-17',outcome:'correct'});
check(()=>assert.equal(overdue.stage,1));
check(()=>assert.equal(overdue.dueDay,'2026-12-20'));
check(()=>assert.deepEqual(schedule(due,{day:'2026-10-19',outcome:'skipped'}),due));
check(()=>assert.deepEqual(schedule(due,{day:'2026-10-19',outcome:'correct',eligible:false}),due));
check(()=>assert.equal(schedule(null,{day:'2026-10-19',outcome:'unscored'}),null));
check(()=>assert.equal(schedule({...due,stage:5},{day:'2026-11-01',outcome:'correct'}).stage,5));
check(()=>assert.equal(addCalendarDays('2028-02-28',1),'2028-02-29'));
check(()=>assert.equal(addCalendarDays('2026-12-31',1),'2027-01-01'));
check(()=>assert.equal(localDay('2026-10-17T16:01:00Z','Asia/Shanghai'),'2026-10-18'));
check(()=>assert.equal(localDay('2026-03-08T07:01:00Z','America/New_York'),'2026-03-08'));
check(()=>assert.throws(()=>addCalendarDays('2026-02-30',1),TypeError));
check(()=>assert.throws(()=>schedule(first,{day:'2026-10-19',outcome:'made-up'}),TypeError));
check(()=>assert.equal(first.stage,0)); // original object remains unchanged
console.log(JSON.stringify({referenceReviewChecks:checks,status:'passed',scope:'Pure reference logic only; no D1 or production app tested.'}));
