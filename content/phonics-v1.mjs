// Original GPC/word-part route. The last stage uses meaning parts, not phoneme counts.
// Word audio is whole-word synthesis; these are not recordings of isolated pure phonemes.
const W = (word, meaning, parts, focus = [1]) => {
  const tiles = parts.split("|");
  return {
    id: word,
    word,
    meaning,
    tiles,
    groups: tiles.map((_, i) => [i]),
    focus,
  };
};
const E = (word, meaning) => ({
  id: word,
  word,
  meaning,
  tiles: [...word],
  groups: [[0], [1, 3], [2]],
  focus: [1],
});
const B = (word, meaning) => W(word, meaning, [...word].join("|"), [0, 1]);
