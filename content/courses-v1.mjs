// Original bilingual lessons. Each three-way practice family shares the same
// family ID so recognition, spelling and ordering cannot masquerade as transfer.
const units = [];
function unit(grade, title, lessons) {
  const unitId = `P${grade}A-U01`;
  units.push(
    ...lessons.map((lesson, index) => ({
      id: `${unitId}-L${index + 1}`,
      unitId,
      unitTitle: title,
      grade,
      term: "A",
      order: index + 1,
      minutes: 6,
      ...lesson,
    })),
  );
}
function lesson(
  title,
  subtitle,
  skill,
  topicIds,
  rule,
  vocabulary,
  facts,
  task,
) {
  return {
    title,
    subtitle,
    skill,
    topicIds,
    rule,
    vocabulary: vocabulary.map(([word, meaning]) => ({ word, meaning })),
    facts,
    task,
  };
}
