const choice = (
  id,
  demand,
  context,
  prompt,
  choices,
  answer,
  explanation,
  hint,
) => ({
  id,
  demand,
  context,
  prompt,
  type: "choice",
  choices,
  answers: [answer],
  explanation,
  hint,
});
const input = (id, demand, context, prompt, answer, explanation, hint) => ({
  id,
  demand,
  context,
  prompt,
  type: "input",
  answers: [answer],
  explanation,
  hint,
});
const repair = (
  id,
  context,
  parts,
  target,
  replacements,
  sentence,
  explanation,
  hint,
) => ({
  id,
  demand: "error-analysis",
  context,
  prompt: "选出有误的部分，填写正确形式。",
  type: "repair",
  editing: { parts: parts.map((text, i) => ({ id: `p${i}`, text })) },
  answers: replacements.map((text) =>
    JSON.stringify([`p${target}`, text.toLowerCase()]),
  ),
  repairs: [{ partId: `p${target}`, replacements }],
  solutionSentences: [sentence],
  explanation,
  hint,
});
